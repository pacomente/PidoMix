def ill_url(emoji: str | None) -> str | None:
    name = ILL.get((emoji or '').replace('\ufe0f', ''))
    return f'/static/ill/{name}.svg' if name else None


def ill(emoji: str | None, size: int = 40, cls: str = 'ill') -> Markup:
    """<img> con la ilustracion 3D, o el emoji comun si no la tenemos."""
    url = ill_url(emoji)
    if url:
        return Markup(f'<img class="{cls}" src="{url}" width="{size}" height="{size}" alt="" loading="lazy">')
    return Markup(f'<span class="{cls} ill-emoji" style="font-size:{int(size * .8)}px" aria-hidden="true">{escape(emoji or "🛍️")}</span>')
